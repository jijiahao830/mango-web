ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "car_card_taglines.json"


def main() -> None:
    carpark = ROOT / "carpark"
    folders = sorted([p.name for p in carpark.iterdir() if p.is_dir() and (p / "car.html").is_file()])
    missing = [f for f in folders if f not in TAGS]
    extra = [k for k in TAGS if k not in folders]
    if missing:
        raise SystemExit(f"TAGS 缺少文件夹: {missing[:5]}{'...' if len(missing)>5 else ''} (共{len(missing)})")
    if extra:
        raise SystemExit(f"TAGS 多余键: {extra[:5]}")
    ordered = {name: TAGS[name] for name in folders}
    OUT.write_text(json.dumps(ordered, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(ordered)} entries)")


if __name__ == "__main__":
    main()
